#Tokens are the smallest units of a Python program.

#Python has five types of tokens:

#Keywords – Reserved words in Python (e.g., if, else, while, for, def).
#Identifiers – Names given to variables, functions, and classes.
#Literals – Constant values assigned to variables (e.g., 10, "Hello", 3.14).
#Operators – Symbols that perform operations (e.g., +, -, *, /).
#Punctuators – Symbols like (), {}, [], ,, :,. used for syntax structuring.

